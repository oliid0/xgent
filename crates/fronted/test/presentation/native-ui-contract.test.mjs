import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { checkNativeContracts, validateNativeContracts } from "../../../../scripts/check-native-ui.mjs";

const nativeViewSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationView.swift", import.meta.url), "utf8");
const nativeLayoutSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationLayout.swift", import.meta.url), "utf8");
const nativeMobileSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationMobile.swift", import.meta.url), "utf8");
const nativeMobileNodeSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationMobileNode.swift", import.meta.url), "utf8");
const nativeDesktopSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationDesktopContent.swift", import.meta.url), "utf8");
const nativeSettingsSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationDesktopSettings.swift", import.meta.url), "utf8");
const nativeMobileSettingsSource = readFileSync(new URL("../../src-tauri/native/apple-ui/PresentationMobileSettings.swift", import.meta.url), "utf8");

function contracts() {
  const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
  return {
    protocol: read("../../src/presentation/protocol.ts"),
    swiftProtocol: read("../../src-tauri/native/apple-ui/PresentationProtocol.swift"),
    types: read("../../src/presentation/types.ts"),
    model: read("../../src-tauri/native/apple-ui/PresentationModel.swift"),
  };
}

test("handwritten native UI shares a checked state/action schema without an Astryx generator", () => {
  const result = checkNativeContracts();
  assert.ok(result.kinds > 40);
  assert.equal(result.properties, 45);
  for (const source of [nativeViewSource, nativeDesktopSource, nativeMobileSource, nativeMobileNodeSource]) {
    assert.doesNotMatch(source, /generatedContent|Generated by/);
  }
});

test("state contract checks reject a missing kind or a field mismatch without generating UI", () => {
  const sources = contracts();
  assert.throws(() => validateNativeContracts({ ...sources, swiftProtocol: sources.swiftProtocol.replace('    case button = "Button"', '') }), /kinds/);
  assert.throws(() => validateNativeContracts({ ...sources, types: sources.types.replace('  focusRequest?: number;', '') }), /properties/);
  assert.throws(() => validateNativeContracts({ ...sources, model: sources.model.replace('    let action: String?', '') }), /properties/);
  assert.throws(() => validateNativeContracts({ ...sources, swiftProtocol: sources.swiftProtocol.replace('["changeText"]', '["changeNumber"]') }), /events/);
});

test("native glass keeps grouped surfaces distinct from floating controls", () => {
  assert.match(nativeViewSource, /var floating: Bool/);
  assert.match(
    nativeViewSource,
    /floating \? material\.popoverOpacity : material\.surfaceOpacity/,
  );
  assert.match(nativeDesktopSource, /XgentActionButton\(node: node, document: document, model: model\)/);
  for (const modifier of ["Insets", "FixedFrame", "BoundsFrame", "TextLayout", "Control"]) {
    assert.match(nativeViewSource, new RegExp(`struct XgentNode${modifier}Modifier: ViewModifier`));
  }
  assert.match(
    nativeViewSource,
    /AnyView\(desktopContent\)[\s\S]*?\.modifier\(XgentNodeFixedFrameModifier\([\s\S]*?\.modifier\(XgentNodeBoundsFrameModifier\(/,
  );
  assert.match(
    nativeLayoutSource,
    /XgentGlassSurface\(radius: CGFloat\(presentationTheme\.radius\.chat\), floating: true\)/,
  );
  assert.match(nativeLayoutSource, /child\.icon == nil \? 0 : 36/);
  assert.match(nativeDesktopSource, /XgentSelector\(node: node, document: document, model: model\)/);
  assert.match(nativeViewSource, /Form \{[\s\S]*?\.formStyle\(\.grouped\)/);
  assert.doesNotMatch(nativeViewSource, /\.presentationBackground\(/);
  assert.match(nativeLayoutSource, /List\(node\.children \?\? \[\]\)/);
  assert.match(nativeLayoutSource, /document\.formFactor == \.mobile[\s\S]*?\.listStyle\(\.insetGrouped\)/);
  assert.match(nativeLayoutSource, /\.listStyle\(\.sidebar\)/);
  assert.match(nativeSettingsSource, /struct XgentDesktopSettingsLayout: View/);
  assert.match(nativeSettingsSource, /geometry\.size\.width >= 760/);
  assert.doesNotMatch(nativeSettingsSource, /minWidth: 900|NavigationSplitView/);
  assert.match(nativeLayoutSource, /HSplitView \{/);
  assert.match(nativeLayoutSource, /@AppStorage\("xgent\.native\.sidebar-width\.v1"\)/);
});

